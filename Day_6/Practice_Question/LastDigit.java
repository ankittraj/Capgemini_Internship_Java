// Write a Java program to accept a number and display its last digit in words using a method in a class.

package Day_6.Practice_Question;

import java.util.Scanner;

class LastDigit {
    void displayLastDigit(int number) {
        int digit = Math.abs(number % 10);

        switch (digit) {
            case 0:
                System.out.println("Zero");
                break;
            case 1:
                System.out.println("One");
                break;
            case 2:
                System.out.println("Two");
                break;
            case 3:
                System.out.println("Three");
                break;
            case 4:
                System.out.println("Four");
                break;
            case 5:
                System.out.println("Five");
                break;
            case 6:
                System.out.println("Six");
                break;
            case 7:
                System.out.println("Seven");
                break;
            case 8:
                System.out.println("Eight");
                break;
            case 9:
                System.out.println("Nine");
                break;
        }
    }

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        System.out.print("Enter a number: ");
        int number = sc.nextInt();

        LastDigit obj = new LastDigit();
        obj.displayLastDigit(number);

        sc.close();
    }
}
